/** Merge a template with overrides into a full UnitDef. */
export function unit(
  id: string,
  name: string,
  faction: UnitDef['faction'],
  template: Template,
  overrides: Partial<UnitDef> & { trainedAt: string; mesh: string },
): UnitDef {
  return {
    id,
    name,
    faction,
    ...template,
    ...overrides,
    tags: overrides.tags ?? template.tags,
    cost: overrides.cost ?? template.cost,
  };
}
